CREATE TABLE IF NOT EXISTS usuario (
    "idUsuario" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "nomeUsuario" TEXT NOT NULL UNIQUE,
    "emailUsuario" TEXT NOT NULL UNIQUE,
    "senhaUsuario" TEXT NOT NULL,
    "planoAssinatura" TEXT NOT NULL DEFAULT 'ESSENCIAL',
    "cicloPlano" TEXT NOT NULL DEFAULT 'MENSAL',
    "validadePlano" TEXT DEFAULT NULL,
    "dataAceiteTermos" TEXT DEFAULT CURRENT_TIMESTAMP,
    "apiToken" TEXT DEFAULT NULL,
    "tokenRecuperacao" TEXT DEFAULT NULL,
    "expiraRecuperacao" BIGINT DEFAULT NULL
);

CREATE TABLE IF NOT EXISTS cliente (
    "idCliente" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "idUsuario" INTEGER NOT NULL DEFAULT 1 REFERENCES usuario("idUsuario") ON DELETE CASCADE,
    "nomeCliente" TEXT NOT NULL,
    "email" TEXT NOT NULL,
    "telefone" TEXT DEFAULT NULL,
    "endereco" TEXT DEFAULT NULL,
    "cidade" TEXT DEFAULT NULL,
    "uf" TEXT DEFAULT NULL
);

CREATE TABLE IF NOT EXISTS fornecedor (
    "idFornecedor" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "idUsuario" INTEGER NOT NULL DEFAULT 1 REFERENCES usuario("idUsuario") ON DELETE CASCADE,
    "nomeFornecedor" TEXT NOT NULL,
    "segmento" TEXT DEFAULT NULL,
    "cnpj" TEXT NOT NULL,
    "email" TEXT DEFAULT NULL,
    "telefone" TEXT DEFAULT NULL,
    "endereco" TEXT DEFAULT NULL,
    "cidade" TEXT DEFAULT NULL,
    "uf" TEXT DEFAULT NULL
);

CREATE TABLE IF NOT EXISTS produto (
    "idProduto" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "idUsuario" INTEGER NOT NULL DEFAULT 1 REFERENCES usuario("idUsuario") ON DELETE CASCADE,
    "idFornecedor" INTEGER DEFAULT NULL,
    "codigoBarras" TEXT DEFAULT NULL,
    "nomeProduto" TEXT NOT NULL,
    "categoria" TEXT DEFAULT NULL,
    "preco" DOUBLE PRECISION NOT NULL DEFAULT 0,
    "precoCusto" DOUBLE PRECISION NOT NULL DEFAULT 0,
    "quantidade" INTEGER NOT NULL DEFAULT 0,
    "estoqueMinimo" INTEGER NOT NULL DEFAULT 10,
    "localizacao" TEXT NOT NULL DEFAULT 'A-01-01',
    "descricao" TEXT DEFAULT NULL,
    "nomeFornecedor" TEXT DEFAULT NULL,
    "lote" TEXT DEFAULT NULL,
    "dataValidade" TEXT DEFAULT NULL,
    "imagem" TEXT DEFAULT NULL
);

CREATE TABLE IF NOT EXISTS movimento (
    "idMovimento" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "idUsuario" INTEGER NOT NULL DEFAULT 1 REFERENCES usuario("idUsuario") ON DELETE CASCADE,
    "codigoPedido" TEXT DEFAULT NULL,
    "idProduto" INTEGER NOT NULL,
    "idCliente" INTEGER DEFAULT NULL,
    "idFornecedor" INTEGER DEFAULT NULL,
    "tipoMovimento" TEXT NOT NULL,
    "quantidade" INTEGER NOT NULL,
    "observacao" TEXT DEFAULT NULL,
    "lote" TEXT DEFAULT NULL,
    "dataValidade" TEXT DEFAULT NULL,
    "motivoAjuste" TEXT DEFAULT NULL,
    "precoUnitario" DOUBLE PRECISION NOT NULL DEFAULT 0,
    "custoUnitario" DOUBLE PRECISION NOT NULL DEFAULT 0,
    "valorTotal" DOUBLE PRECISION NOT NULL DEFAULT 0,
    "dataMovimento" TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "dataDevolucao" TEXT DEFAULT NULL
);

-- Índices para performance Multi-Tenant
CREATE INDEX IF NOT EXISTS idx_cli_usuario ON cliente ("idUsuario");
CREATE INDEX IF NOT EXISTS idx_forn_usuario ON fornecedor ("idUsuario");
CREATE INDEX IF NOT EXISTS idx_prod_usuario ON produto ("idUsuario");
CREATE INDEX IF NOT EXISTS idx_mov_usuario ON movimento ("idUsuario");

-- Desabilita RLS caso use a chave anon diretamente no backend Serverless
ALTER TABLE usuario DISABLE ROW LEVEL SECURITY;
ALTER TABLE cliente DISABLE ROW LEVEL SECURITY;
ALTER TABLE fornecedor DISABLE ROW LEVEL SECURITY;
ALTER TABLE produto DISABLE ROW LEVEL SECURITY;
ALTER TABLE movimento DISABLE ROW LEVEL SECURITY;

